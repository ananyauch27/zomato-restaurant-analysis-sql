-- Best value restaurants — high rating, low cost, high votes

SELECT * FROM zomatodata;

SELECT RestaurantName, City, Cuisines, Average_Cost_for_two, Rating, Votes
FROM zomatodata WHERE CountryCode = 1
  AND Rating >= 4.0
  AND Average_Cost_for_two <= 500
  AND Votes >= 200
ORDER BY Rating DESC, Votes DESC
LIMIT 20;


-- Price range vs average rating
SELECT CASE
    WHEN Average_Cost_for_two < 300 THEN 'Budget (under 300)'
    WHEN Average_Cost_for_two BETWEEN 300 AND 700 THEN 'Mid (300-700)'
    WHEN Average_Cost_for_two BETWEEN 700 AND 1500 THEN 'Premium (700-1500)'
    ELSE 'Fine Dining (1500+)'
  END AS price_category,
  COUNT(*) AS restaurant_count,
  ROUND(AVG(Rating), 2) AS avg_rating,
  ROUND(AVG(Votes), 0) AS avg_votes
FROM zomatodata WHERE CountryCode = 1 AND Rating > 0
GROUP BY price_category ORDER BY avg_rating DESC;

