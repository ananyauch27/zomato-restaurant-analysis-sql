-- WHICH COUNTRIES AND HOW MANY RESTAURANTS WITH PERCENTAGE PROVIDES ONLINE DELIVERY OPTION

CREATE OR REPLACE VIEW COUNTRY_REST AS
SELECT COUNTRY_NAME, COUNT(RestaurantID) AS REST_COUNT
FROM zomatodata GROUP BY COUNTRY_NAME;

SELECT * FROM COUNTRY_REST
ORDER BY REST_COUNT DESC;

SELECT A.COUNTRY_NAME, COUNT(A.RestaurantID) AS TOTAL_REST,
    ROUND( COUNT(A.RestaurantID) / B.REST_COUNT * 100,2) AS ONLINE_DELIVERY_PERCENTAGE
FROM zomatodata A JOIN COUNTRY_REST B ON A.COUNTRY_NAME = B.COUNTRY_NAME
WHERE A.Has_Online_delivery = 'YES'
GROUP BY A.COUNTRY_NAME, B.REST_COUNT ORDER BY TOTAL_REST DESC;

